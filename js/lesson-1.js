// Запропонуйте користувачу ввести число за допомогою prompt().
// Збережіть введене значення у змінну number.
// Перевірте, чи дорівнює змінна number числу 10:
//    Якщо так – виведіть повідомлення 'Вірно' у alert().
//    Якщо ні – виведіть 'Невірно'. 

// Підказка: prompt завжди повертає рядок (String), тому перед перевіркою  
// перетворіть значення на число за допомогою Number().



// Запропонуйте користувачу ввести число
let input = prompt("Будь ласка, введіть число:");

// Перевіряємо, чи користувач не натиснув "Скасувати"
if (input === null) {
    alert("Ви скасували введення");
} 
// Додаємо перевірку на порожній рядок
else if (input.trim() === "") {
    alert("Ви нічого не ввели!");
} 
else {
    // Конвертуємо в число
    let number = Number(input);
    
    // Перевіряємо, чи це дійсно число (не NaN)
    if (isNaN(number)) {
        alert("Будь ласка, введіть коректне число!");
    } else {
        // Перевіряємо, чи дорівнює 10
        if (number === 10) {
            alert('Вірно');
        } else {
            alert('Невірно');
        }
    }
}